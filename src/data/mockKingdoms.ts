import type { Building, Kingdom } from "../types";

function mkBuilding(
  kingdomId: string,
  type: string,
  category: Building["category"],
  level: number,
  progress: number,
  required: number,
  x: number,
  z: number,
  description: string,
): Building {
  return {
    id: `${kingdomId}-${type.toLowerCase().replace(/\s/g, "-")}`,
    kingdomId,
    type,
    category,
    level,
    progress,
    progressRequired: required,
    position: [x, z],
    description,
  };
}

